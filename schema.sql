-- ImmuneFleet Cloud Database Schema for Supabase
-- Paste and execute this in your Supabase SQL Editor (https://supabase.com/dashboard/project/_/sql)

-- 1. Antibodies Table (Synthesized & Deployed Fleet Immunizations)
CREATE TABLE IF NOT EXISTS public.antibodies (
    id TEXT PRIMARY KEY,
    target_id TEXT NOT NULL,
    action TEXT NOT NULL,
    threat TEXT NOT NULL,
    rule_json JSONB NOT NULL,
    signature TEXT NOT NULL,
    deployed_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- 2. Fleet Event Log (Immutable Security Audit Trail)
CREATE TABLE IF NOT EXISTS public.fleet_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message TEXT NOT NULL,
    event_type TEXT DEFAULT 'info',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- 3. Incident Reports (On-car Intrusion Detections awaiting Quorum)
CREATE TABLE IF NOT EXISTS public.incident_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id INT NOT NULL,
    rule_key TEXT NOT NULL,
    signature TEXT NOT NULL,
    reported_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW())
);

-- Enable Row Level Security (RLS)
ALTER TABLE public.antibodies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fleet_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.incident_reports ENABLE ROW LEVEL SECURITY;

-- Allow read and write for demo application (Anon and Service role)
DROP POLICY IF EXISTS "Allow demo antibodies read-write" ON public.antibodies;
CREATE POLICY "Allow demo antibodies read-write" ON public.antibodies
    FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow demo events read-write" ON public.fleet_events;
CREATE POLICY "Allow demo events read-write" ON public.fleet_events
    FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow demo reports read-write" ON public.incident_reports;
CREATE POLICY "Allow demo reports read-write" ON public.incident_reports
    FOR ALL USING (true) WITH CHECK (true);
